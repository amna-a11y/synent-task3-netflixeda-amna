import pandas as pd
import matplotlib.pyplot as plt
from google.colab import files

print(" Upload Netflix Dataset (CSV file)")
uploaded = files.upload()

file_name = list(uploaded.keys())[0]
df = pd.read_csv(file_name)
print("\n Dataset Preview:")
print(df.head())
if 'date_added' in df.columns:
    df['date_added'] = pd.to_datetime(df['date_added'], errors='coerce')
    df['year_added'] = df['date_added'].dt.year
if 'type' in df.columns:
    plt.figure()
    df['type'].value_counts().plot(kind='pie', autopct='%1.1f%%')
    plt.title("Content Distribution (Movies vs TV Shows)")
    plt.ylabel("")
    plt.show()
if 'year_added' in df.columns:
    yearly = df['year_added'].value_counts().sort_index()

    plt.figure()
    yearly.plot(kind='line', marker='o')
    plt.title("Netflix Content Growth Over Time")
    plt.xlabel("Year")
    plt.ylabel("Number of Titles")
    plt.grid()
    plt.show()
if 'country' in df.columns:
    top_countries = df['country'].value_counts().head(10)

    plt.figure()
    top_countries.sort_values().plot(kind='barh')
    plt.title("Top 10 Content Producing Countries")
    plt.xlabel("Number of Titles")
    plt.ylabel("Country")
    plt.show()
if 'rating' in df.columns:
    plt.figure()
    df['rating'].value_counts().head(10).plot(kind='bar')
    plt.title("Most Common Content Ratings")
    plt.xlabel("Rating")
    plt.ylabel("Count")
    plt.xticks(rotation=45)
    plt.show()

if 'release_year' in df.columns:
    plt.figure()
    df['release_year'].plot(kind='hist', bins=20)
    plt.title("Distribution of Release Years")
    plt.xlabel("Release Year")
    plt.ylabel("Frequency")
    plt.show()
if 'type' in df.columns and 'year_added' in df.columns:
    grouped = df.groupby(['year_added', 'type']).size().unstack()

    plt.figure()
    grouped.plot(kind='line', marker='o')
    plt.title("Movies vs TV Shows Trend Over Time")
    plt.xlabel("Year")
    plt.ylabel("Count")
    plt.grid()
    plt.show()